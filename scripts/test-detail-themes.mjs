import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

const root = path.resolve('public/experience');
const css = fs.readFileSync(path.join(root, 'detail-themes.css'), 'utf8');
const app = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const ast = postcss.parse(css);
assert.ok(app.includes("$('reading-detail-dialog').dataset.readingMode = currentReading.mode;"));
for (const mode of ['saju', 'ziwei']) assert.ok(css.includes(`[data-reading-mode='${mode}']`));
for (const file of ['detail-zodiac-sky.svg', 'detail-saju-elements.svg', 'detail-ziwei-palaces.svg']) {
  assert.ok(css.includes(`url('./assets/${file}')`));
  const svg = fs.readFileSync(path.join(root, 'assets', file), 'utf8');
  assert.match(svg, /<svg[^>]*viewBox="0 0 720 1000"/);
  assert.ok(!/<(?:script|text|foreignObject|image)\b/i.test(svg), 'motifs stay static decorative vectors, not fake personal charts or remote content');
}
const headingMarkup = html.match(/<header class="reading-detail-heading">([\s\S]*?)<\/header>/)?.[1] || '';
const bannerMarkup = headingMarkup.match(/<div class="reading-detail-banner">([\s\S]*)<\/div>/)?.[1] || '';
const contextMarkup = headingMarkup.match(/<div class="reading-detail-context">([\s\S]*?)<\/div>/)?.[1] || '';
assert.match(bannerMarkup.trim(), /^<h2 id="reading-detail-title">[^<>]*(?:<br\s*\/?>[^<>]*)*<\/h2><div class="reading-detail-context">/);
assert.ok(bannerMarkup.includes('reading-detail-label') && bannerMarkup.includes('reading-detail-intro'), 'title and small copy both belong inside the banner');
assert.match(contextMarkup, /<p id="reading-detail-label" class="eyebrow"><\/p>/);
assert.match(contextMarkup, /<p id="reading-detail-intro"><\/p>/);
assert.ok(bannerMarkup.indexOf('reading-detail-context') > bannerMarkup.indexOf('reading-detail-title'), 'the small descriptions sit beneath the title within the same banner');
assert.ok(html.includes('aria-labelledby="reading-detail-title"'), 'the accessible dialog name is retained');
assert.match(html, /<\/div><button id="reading-detail-top"[^>]*data-detail-top[^>]*hidden>/, 'TOP remains a direct dialog sibling outside the sheet');
assert.ok(html.includes('id="detail-download-pdf"') && html.includes('id="detail-pdf-status"'), 'the PDF button and status remain intact');

let dialogRule, sheetRule, layerRule, bannerBoxRule, bannerRule, headingTextRule, titleRule, contextRule, labelRule, introRule, downloadRule;
const mobileTitleRules = [];
ast.walkRules((rule) => {
  if (rule.selector === '.reading-detail-dialog') dialogRule ??= rule;
  if (rule.selector === '.reading-detail-dialog .reading-detail-sheet') sheetRule ??= rule;
  if (rule.selector === '.reading-detail-dialog .reading-detail-sheet::before') layerRule = rule;
  if (rule.selector === '.reading-detail-dialog .reading-detail-banner') bannerBoxRule ??= rule;
  if (rule.selector === '.reading-detail-banner::before') bannerRule ??= rule;
  if (rule.selector === '.reading-detail-banner > *') headingTextRule = rule;
  if (rule.selector === '.reading-detail-dialog .reading-detail-context') contextRule ??= rule;
  if (rule.selector === '.reading-detail-dialog .reading-detail-context .eyebrow') labelRule ??= rule;
  if (rule.selector === '.reading-detail-dialog #reading-detail-intro') introRule ??= rule;
  if (rule.selector === '.reading-detail-dialog .reading-detail-heading h2') {
    titleRule ??= rule;
    if (rule.parent.type === 'atrule' && rule.parent.name === 'media') mobileTitleRules.push(rule);
  }
  if (rule.selector === '.reading-detail-dialog .reading-detail-download') downloadRule = rule;
});
const props = (rule) => Object.fromEntries(rule.nodes.filter((node) => node.type === 'decl').map((node) => [node.prop, node.value]));
const dialog = props(dialogRule);
assert.equal(dialog['background-repeat'], 'no-repeat', 'long report backgrounds must not form tile seams');
assert.equal(dialog['background-attachment'], 'scroll', 'the background belongs to the dialog viewport, not its scrolling content');
assert.equal(dialog['background-size'], 'cover, cover');
assert.ok(!Object.hasOwn(dialog, 'overflow') && !Object.hasOwn(dialog, 'overflow-y'), 'themes must not change the existing dialog scrollport');
assert.equal(dialog['--detail-theme-wash'], '#f5f3fa80', 'a 50 percent wash belongs to the art, not to text');
assert.ok(dialog['background-image'].includes('linear-gradient(var(--detail-theme-wash)') && dialog['background-image'].includes('var(--detail-theme-art)'));
assert.equal(props(sheetRule).background, 'transparent', 'the report sheet reveals the continuous dialog background');
assert.equal(props(layerRule).content, 'none');
assert.equal(props(layerRule).display, 'none', 'disable the previous repeated sheet layer');
assert.ok(!css.includes('repeat-y'), 'there must be no repeating vertical motif');
assert.ok(props(bannerRule).background.includes('sai-adult-reflection.png'), 'existing reflection artwork is used as the heading banner');
assert.ok(props(bannerRule).background.includes('right 42% / cover no-repeat'), 'cover fills banners even when a long intro expands their height');
assert.equal(props(bannerRule).transform, 'scale(1.35)');assert.equal(props(bannerRule)['transform-origin'], 'right center');
assert.equal(props(bannerRule).position, 'absolute');
assert.equal(props(bannerRule).inset, '0');
assert.equal(props(bannerRule).opacity, '.35', 'only the banner picture is faded to 35 percent, five percentage points lighter');
assert.equal(props(bannerRule)['pointer-events'], 'none');
assert.ok(!Object.hasOwn(props(bannerRule), 'height'), 'the image must overlay the title region, not create a separate tall banner');
assert.equal(props(headingTextRule)['z-index'], '1', 'the title stays above the decorative picture');
assert.ok(props(bannerBoxRule)['border-radius'] && props(bannerBoxRule).overflow === 'hidden');
assert.equal(props(bannerBoxRule).position, 'relative');
assert.equal(props(titleRule)['font-weight'], '700', 'the banner title is one weight step heavier');
assert.equal(props(titleRule)['font-synthesis'], 'none', 'avoid inconsistent browser-synthesized weight on the existing AritaBuri face');
assert.equal(props(titleRule)['-webkit-text-stroke'], '.15px currentColor', 'a subtle title-only stroke makes the heavier step visible with the bundled 600 face');
assert.equal(props(labelRule)['font-weight'], '600', 'banner classification moves from 500 to 600');
assert.equal(props(introRule)['font-weight'], '500', 'banner introduction moves from 400 to 500');
assert.equal(props(titleRule).width, '100%', 'the title spans the entire banner rather than its right side');
assert.equal(props(titleRule).margin, '0');
assert.equal(props(bannerBoxRule)['text-align'], 'center');assert.equal(props(bannerBoxRule)['flex-direction'], 'column');
assert.equal(props(contextRule)['text-align'], 'center', 'small copy shares the centered alignment inside the banner');
assert.equal(mobileTitleRules.length, 2);
assert.ok(mobileTitleRules.some((rule) => rule.parent.params === '(max-width: 600px)' && props(rule)['font-size'] === '25px'));
assert.ok(mobileTitleRules.some((rule) => rule.parent.params === '(max-width: 360px)' && props(rule)['font-size'] === '22px'), 'the narrowest title retains readable two-line sizing');
for (const rule of mobileTitleRules) assert.ok(!Object.hasOwn(props(rule), 'width') && !Object.hasOwn(props(rule), 'margin'), 'mobile titles retain full-width centered layout');
ast.walkRules((rule) => {
  if (rule.parent.type !== 'atrule' || rule.parent.name !== 'media' || !rule.parent.params.includes('max-width')) return;
  if (!rule.selector.includes('.reading-detail-banner::before')) return;
  const mobile = props(rule);
  const shortIntro = rule.selector.includes(':not(');
  assert.equal(mobile['background-position'], shortIntro ? '30% 40%' : '72% 40%');
  assert.equal(mobile.transform, shortIntro ? 'translateY(22px) scale(1.55)' : 'translateY(12px) scale(1.2)');
});
assert.equal(props(downloadRule).background, 'transparent', 'remove the large white PDF wrapper, preserving the button');
assert.equal(props(downloadRule).padding, '0');
assert.equal(props(downloadRule)['border-radius'], '0');
assert.ok(css.includes('@media (max-width: 360px)') && css.includes('@media (forced-colors: active)'));
assert.ok(css.includes('background: #fffffff2'), 'text is held on opaque white cards');
assert.ok(!css.includes('animation:'), 'long reports do not animate behind the text');
console.log('PASS detail themes: 35% banner image, centered 700/600/500 banner text, unchanged left/lower responsive image crop, seamless 50% dialog background, TOP/PDF contracts.');
